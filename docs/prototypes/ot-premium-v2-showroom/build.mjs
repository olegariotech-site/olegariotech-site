import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {order,renderTab,renderCase,escapeHTML} from './templates.mjs';
const dir=new URL('./',import.meta.url);
const source=await readFile(new URL('../../../index.html',dir),'utf8');
const match=source.match(/const projects=(\{[\s\S]*?\n\});/);
if(!match)throw Error('Canonical projects JSON not found; refuse to build a parallel catalog.');
const projects=JSON.parse(match[1]);
// Follow the actual boot call, not the stale is-active class in the pre-JS markup.
const initial=source.match(/renderSolution\('presenca',false\);renderProject\('([^']+)'\)/)?.[1];
if(!initial||!projects[initial]||order.some(key=>!projects[key])||Object.keys(projects).length!==6)throw Error('Portfolio or initial selection changed; inspect canonical source.');
const assets=JSON.parse(await readFile(new URL('./assets/media.json',dir),'utf8'));
const sourceSHA256=createHash('sha256').update(match[1]).digest('hex');
const data=`// GENERATED by build.mjs from the canonical projects in /index.html. Do not edit.\nexport const sourceSHA256=${JSON.stringify(sourceSHA256)};\nexport const initial=${JSON.stringify(initial)};\nexport const projects=${JSON.stringify(projects,null,2)};\nexport const media=${JSON.stringify(assets,null,2)};\n`;
const template=await readFile(new URL('./page.template.html',dir),'utf8');
const html=template.replace('<!-- REAL_TABS -->',order.filter(key=>key!=='navalha').map(key=>renderTab(key,projects[key],initial,assets[key])).join('\n')).replace('<!-- CONCEPT_TAB -->',renderTab('navalha',projects.navalha,initial,assets.navalha)).replace('<!-- INITIAL_CASE -->',renderCase(initial,projects[initial],assets[initial])).replaceAll('{{INITIAL}}',initial).replaceAll('{{INITIAL_TITLE}}',escapeHTML(projects[initial].title)).split('\n').map(line=>line.trimEnd()).join('\n');
if(process.argv.includes('--check')){
 for(const [name,expected] of [['projects.generated.mjs',data],['index.html',html]])if(await readFile(new URL(name,dir),'utf8')!==expected)throw Error(`${name} is stale; run node ${fileURLToPath(import.meta.url)}`);
 console.log('Canonical snapshot and static initial markup are current.');
}else{
 await writeFile(new URL('projects.generated.mjs',dir),data);
 await writeFile(new URL('index.html',dir),html);
 console.log('Built isolated showroom from canonical projects:',initial,sourceSHA256);
}
